SUPPORTED_LANGS = tuple(WEB_STRINGS.keys())


def pick_language(cookie_value: str | None, accept_language: str | None) -> str:
    if cookie_value in WEB_STRINGS:
        return cookie_value
    if accept_language:
        ranked: list[tuple[float, str]] = []
        for part in accept_language.split(",")[:16]:
            pieces = part.strip().split(";")
            tag = pieces[0].strip().lower()[:16]
            quality = 1.0
            for param in pieces[1:]:
                param = param.strip()
                if param.startswith("q="):
                    try:
                        quality = float(param[2:])
                    except ValueError:
                        quality = 0.0
            ranked.append((quality, tag))
        ranked.sort(key=lambda item: item[0], reverse=True)
        for _, tag in ranked:
            primary = tag.split("-")[0]
            if primary in WEB_STRINGS:
                return primary
    return "en"
